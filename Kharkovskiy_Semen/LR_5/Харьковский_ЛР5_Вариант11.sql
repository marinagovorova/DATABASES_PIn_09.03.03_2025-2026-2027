SELECT n.nspname AS schema_name,
       p.proname AS routine_name,
       CASE p.prokind WHEN 'p' THEN 'PROCEDURE' ELSE 'FUNCTION' END AS routine_kind
FROM pg_proc p
JOIN pg_namespace n ON n.oid = p.pronamespace
WHERE n.nspname = 'autoservice'
  AND (LEFT(p.proname, 2) = 'p_' OR LEFT(p.proname, 3) = 'fn_')
ORDER BY routine_kind, routine_name;

SELECT event_object_table AS table_name,
       trigger_name,
       action_timing,
       event_manipulation
FROM information_schema.triggers
WHERE trigger_schema = 'autoservice'
  AND LEFT(trigger_name, 4) = 'trg_'
ORDER BY trigger_name, event_manipulation;


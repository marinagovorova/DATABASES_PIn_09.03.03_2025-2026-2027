-- 2.7. Автоматическое закрытие предыдущего периода цены и защита от пересечений.
CREATE OR REPLACE FUNCTION fn_manage_work_price_period()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    UPDATE work_prices
       SET valid_to = NEW.valid_from - 1
     WHERE work_type_id = NEW.work_type_id
       AND valid_to IS NULL
       AND valid_from < NEW.valid_from;

    IF EXISTS (
        SELECT 1
          FROM work_prices wp
         WHERE wp.work_type_id = NEW.work_type_id
           AND DATERANGE(
                   wp.valid_from,
                   COALESCE(wp.valid_to, 'infinity'::DATE),
                   '[]'
               ) && DATERANGE(
                   NEW.valid_from,
                   COALESCE(NEW.valid_to, 'infinity'::DATE),
                   '[]'
               )
    ) THEN
        RAISE EXCEPTION 'Период новой цены пересекается с существующим периодом';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_manage_work_price_period ON work_prices;
CREATE TRIGGER trg_manage_work_price_period
BEFORE INSERT ON work_prices
FOR EACH ROW EXECUTE FUNCTION fn_manage_work_price_period();


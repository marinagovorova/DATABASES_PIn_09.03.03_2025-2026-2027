-- 1.1. Повышение цены деталей для автомобилей Ford на 10%.
-- Параметры позволяют использовать процедуру и для другой марки/процента.
CREATE OR REPLACE PROCEDURE p_increase_part_prices(
    IN p_brand_name TEXT DEFAULT 'Ford',
    IN p_percent NUMERIC DEFAULT 10,
    INOUT p_updated_rows INTEGER DEFAULT 0
)
LANGUAGE plpgsql
AS $$
BEGIN
    IF p_percent <= 0 OR p_percent > 100 THEN
        RAISE EXCEPTION 'Процент повышения должен быть в диапазоне (0; 100]';
    END IF;

    UPDATE parts p
       SET unit_price = ROUND(p.unit_price * (1 + p_percent / 100.0), 2)
     WHERE EXISTS (
         SELECT 1
           FROM part_brand_compatibility pbc
           JOIN car_brands b ON b.brand_id = pbc.brand_id
          WHERE pbc.part_id = p.part_id
            AND LOWER(b.brand_name) = LOWER(p_brand_name)
     );

    GET DIAGNOSTICS p_updated_rows = ROW_COUNT;
    RAISE NOTICE 'Обновлено цен деталей: %', p_updated_rows;
END;
$$;

-- 1.2. Повышение разряда мастеров, отремонтировавших больше 3 автомобилей.
-- Один завершённый заказ соответствует ремонту одного автомобиля.
CREATE OR REPLACE PROCEDURE p_promote_productive_masters(
    IN p_min_repaired_cars INTEGER DEFAULT 3,
    INOUT p_promoted_rows INTEGER DEFAULT 0
)
LANGUAGE plpgsql
AS $$
BEGIN
    IF p_min_repaired_cars < 0 THEN
        RAISE EXCEPTION 'Минимальное число ремонтов не может быть отрицательным';
    END IF;

    WITH productive_masters AS (
        SELECT wa.master_id
          FROM work_assignments wa
          JOIN order_services os ON os.order_service_id = wa.order_service_id
          JOIN orders o ON o.order_id = os.order_id
         WHERE o.actual_end_date IS NOT NULL
         GROUP BY wa.master_id
        HAVING COUNT(DISTINCT o.order_id) > p_min_repaired_cars
    )
    UPDATE employees e
       SET grade = LEAST(e.grade + 1, 6)
      FROM productive_masters pm
     WHERE e.employee_id = pm.master_id
       AND e.grade IS NOT NULL
       AND e.grade < 6;

    GET DIAGNOSTICS p_promoted_rows = ROW_COUNT;
    RAISE NOTICE 'Повышен разряд мастеров: %', p_promoted_rows;
END;
$$;

-- 1.3. Число автомобилей, отремонтированных каждым мастером за квартал.
-- Результат возвращается через курсор, что позволяет получить набор строк из CALL.
CREATE OR REPLACE PROCEDURE p_repaired_cars_by_master(
    IN p_quarter_start DATE DEFAULT DATE_TRUNC('quarter', CURRENT_DATE)::DATE,
    INOUT p_result REFCURSOR DEFAULT 'quarter_repair_counts'
)
LANGUAGE plpgsql
AS $$
BEGIN
    IF p_quarter_start IS NULL THEN
        RAISE EXCEPTION 'Дата начала квартала не задана';
    END IF;

    OPEN p_result FOR
        SELECT e.employee_id,
               e.last_name,
               e.first_name,
               COUNT(DISTINCT o.order_id) AS repaired_car_count
          FROM employees e
          JOIN positions pos ON pos.position_id = e.position_id
          LEFT JOIN work_assignments wa ON wa.master_id = e.employee_id
          LEFT JOIN order_services os ON os.order_service_id = wa.order_service_id
          LEFT JOIN orders o
            ON o.order_id = os.order_id
           AND o.actual_end_date >= p_quarter_start
           AND o.actual_end_date < p_quarter_start + INTERVAL '3 months'
         WHERE pos.position_name = 'мастер'
         GROUP BY e.employee_id, e.last_name, e.first_name
         ORDER BY repaired_car_count DESC, e.last_name, e.first_name;
END;
$$;


-- 2.1. Проверка специализации назначаемого мастера.
CREATE OR REPLACE FUNCTION fn_check_master_qualification()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_work_type_id INTEGER;
BEGIN
    SELECT os.work_type_id
      INTO v_work_type_id
      FROM order_services os
     WHERE os.order_service_id = NEW.order_service_id;

    IF EXISTS (
        SELECT 1 FROM work_type_specializations wts
        WHERE wts.work_type_id = v_work_type_id
    ) AND EXISTS (
        SELECT 1
          FROM work_type_specializations wts
         WHERE wts.work_type_id = v_work_type_id
           AND NOT EXISTS (
               SELECT 1
                 FROM employee_specializations es
                WHERE es.employee_id = NEW.master_id
                  AND es.specialization_id = wts.specialization_id
           )
    ) THEN
        RAISE EXCEPTION
            'Мастер % не имеет специализации, требуемой для вида работы %',
            NEW.master_id, v_work_type_id;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_assignment_master_qualification ON work_assignments;
CREATE TRIGGER trg_assignment_master_qualification
BEFORE INSERT OR UPDATE OF master_id, order_service_id ON work_assignments
FOR EACH ROW EXECUTE FUNCTION fn_check_master_qualification();

-- 2.2. Автоматическое завершение услуги и заказа.
CREATE OR REPLACE FUNCTION fn_sync_service_and_order_completion()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_order_id INTEGER;
BEGIN
    IF NEW.completed_at IS NOT NULL
       AND OLD.completed_at IS DISTINCT FROM NEW.completed_at THEN

        IF NOT EXISTS (
            SELECT 1
              FROM work_assignments wa
             WHERE wa.order_service_id = NEW.order_service_id
               AND wa.completed_at IS NULL
        ) THEN
            UPDATE order_services
               SET service_status = 'выполнена'
             WHERE order_service_id = NEW.order_service_id;
        END IF;

        SELECT os.order_id
          INTO v_order_id
          FROM order_services os
         WHERE os.order_service_id = NEW.order_service_id;

        IF EXISTS (
            SELECT 1 FROM order_services os WHERE os.order_id = v_order_id
        ) AND NOT EXISTS (
            SELECT 1
              FROM order_services os
             WHERE os.order_id = v_order_id
               AND os.service_status <> 'выполнена'
        ) THEN
            UPDATE orders
               SET actual_end_date = COALESCE(actual_end_date, CURRENT_DATE),
                   status = 'готов'
             WHERE order_id = v_order_id;
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_assignment_completion_sync ON work_assignments;
CREATE TRIGGER trg_assignment_completion_sync
AFTER UPDATE OF completed_at ON work_assignments
FOR EACH ROW EXECUTE FUNCTION fn_sync_service_and_order_completion();

-- 2.3. Проверка остатка и списание детали автомастерской.
CREATE OR REPLACE FUNCTION fn_consume_inventory_part()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_workshop_id INTEGER;
    v_stock INTEGER;
BEGIN
    IF NEW.source = 'автомастерская' THEN
        SELECT ct.workshop_id
          INTO v_workshop_id
          FROM order_services os
          JOIN orders o ON o.order_id = os.order_id
          JOIN contracts ct ON ct.contract_id = o.contract_id
         WHERE os.order_service_id = NEW.order_service_id;

        SELECT i.quantity
          INTO v_stock
          FROM inventory i
         WHERE i.workshop_id = v_workshop_id
           AND i.part_id = NEW.part_id
         FOR UPDATE;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Деталь % отсутствует на складе мастерской %',
                NEW.part_id, v_workshop_id;
        END IF;
        IF v_stock < NEW.quantity THEN
            RAISE EXCEPTION 'Недостаточный остаток детали %: доступно %, требуется %',
                NEW.part_id, v_stock, NEW.quantity;
        END IF;

        UPDATE inventory
           SET quantity = quantity - NEW.quantity
         WHERE workshop_id = v_workshop_id AND part_id = NEW.part_id;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_used_part_consume_inventory ON used_parts;
CREATE TRIGGER trg_used_part_consume_inventory
BEFORE INSERT ON used_parts
FOR EACH ROW EXECUTE FUNCTION fn_consume_inventory_part();

-- 2.4. Возврат детали на склад при удалении записи об использовании.
CREATE OR REPLACE FUNCTION fn_restore_inventory_part()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_workshop_id INTEGER;
BEGIN
    IF OLD.source = 'автомастерская' THEN
        SELECT ct.workshop_id
          INTO v_workshop_id
          FROM order_services os
          JOIN orders o ON o.order_id = os.order_id
          JOIN contracts ct ON ct.contract_id = o.contract_id
         WHERE os.order_service_id = OLD.order_service_id;

        UPDATE inventory
           SET quantity = quantity + OLD.quantity
         WHERE workshop_id = v_workshop_id AND part_id = OLD.part_id;
    END IF;

    RETURN OLD;
END;
$$;

DROP TRIGGER IF EXISTS trg_used_part_restore_inventory ON used_parts;
CREATE TRIGGER trg_used_part_restore_inventory
AFTER DELETE ON used_parts
FOR EACH ROW EXECUTE FUNCTION fn_restore_inventory_part();

-- 2.5. Аудит вставки, изменения и удаления стоимости работ.
CREATE OR REPLACE FUNCTION fn_audit_work_price()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO work_price_audit
            (work_price_id, work_type_id, operation,
             new_labor_price, new_valid_from, new_valid_to)
        VALUES
            (NEW.work_price_id, NEW.work_type_id, TG_OP,
             NEW.labor_price, NEW.valid_from, NEW.valid_to);
        RETURN NEW;
    ELSIF TG_OP = 'UPDATE' THEN
        INSERT INTO work_price_audit
            (work_price_id, work_type_id, operation,
             old_labor_price, new_labor_price,
             old_valid_from, old_valid_to, new_valid_from, new_valid_to)
        VALUES
            (NEW.work_price_id, NEW.work_type_id, TG_OP,
             OLD.labor_price, NEW.labor_price,
             OLD.valid_from, OLD.valid_to, NEW.valid_from, NEW.valid_to);
        RETURN NEW;
    ELSE
        INSERT INTO work_price_audit
            (work_price_id, work_type_id, operation,
             old_labor_price, old_valid_from, old_valid_to)
        VALUES
            (OLD.work_price_id, OLD.work_type_id, TG_OP,
             OLD.labor_price, OLD.valid_from, OLD.valid_to);
        RETURN OLD;
    END IF;
END;
$$;

DROP TRIGGER IF EXISTS trg_work_price_audit ON work_prices;
CREATE TRIGGER trg_work_price_audit
AFTER INSERT OR UPDATE OR DELETE ON work_prices
FOR EACH ROW EXECUTE FUNCTION fn_audit_work_price();


CREATE TABLE IF NOT EXISTS part_brand_compatibility (
    compatibility_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    part_id           INTEGER NOT NULL,
    brand_id          INTEGER NOT NULL,
    CONSTRAINT fk_part_compatibility_part FOREIGN KEY (part_id)
        REFERENCES parts (part_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_part_compatibility_brand FOREIGN KEY (brand_id)
        REFERENCES car_brands (brand_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT uq_part_brand_compatibility UNIQUE (part_id, brand_id)
);

